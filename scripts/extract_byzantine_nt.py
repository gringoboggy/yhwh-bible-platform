"""scripts/extract_byzantine_nt.py — ingest the Greek New Testament (Robinson-Pierpont
Byzantine Majority Text) into the project's translation store (Phase 2 of the
fully-customizable-builder roadmap; the Greek-NT spine).

Source + license: byztxt/byzantine-majority-text, ``csv-unicode/ccat/no-variants/*.csv``
— accented polytonic Greek Unicode, released into the Public Domain (Unlicense). The
text is the Robinson-Pierpont Byzantine/Majority text (the ecclesiastical-text family
underlying the KJV's TR), so versification is KJV-standard: identity for all 27 books
except the Romans doxology (KJV 16:25-27 sits at the end of ch14 in the Byzantine
text). The accented Unicode was chosen over byztxt's transliterated Scrivener TR so
the Greek NT popups match the accented Swete LXX popups.

Pipeline (parallels scripts/extract_lxx_swete.py):

    _acquire/byzantine-majority-text/csv-unicode/ccat/no-variants/<BOOK>.csv  (chapter,verse,text)
        -> versification remap (versification.byzantine_to_kjv)  -> canonical KJV coords
        -> content/translations/byzantine-greek/<code>.py        VERSES = [(ch, vs, text)]
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
TRANSLATIONS_DIR = REPO / "content" / "translations"
DEFAULT_SOURCE = REPO.parent / "_acquire" / "byzantine-majority-text" / "csv-unicode" / "ccat" / "no-variants"
TRANSLATION_ID = "byzantine-greek"

# The pilcrow is a paragraph marker in the source, not readable text.
_PILCROW_RE = re.compile(r"¶")


def _clean_greek_nt(text: str) -> str:
    return re.sub(r"\s+", " ", _PILCROW_RE.sub("", text)).strip()


def parse_csv(path) -> list[tuple[int, int, str]]:
    """Parse a byztxt ``chapter,verse,text`` CSV into ``[(chapter, verse, text), ...]``."""
    out: list[tuple[int, int, str]] = []
    with open(path, encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            out.append((int(row["chapter"]), int(row["verse"]), row["text"]))
    return out


def build_verses(src_dir) -> tuple[dict[str, list[tuple[int, int, str]]], dict]:
    """Read every ``<BOOK>.csv``, remap to canonical KJV via ``byzantine_to_kjv``, and
    group by project code. Returns ``({code: [(ch, vs, text), ...] sorted}, stats)``."""
    from scripts.core.versification import byzantine_to_kjv

    by_code: dict[str, dict[tuple[int, int], str]] = {}
    omitted = 0
    collisions: list[tuple] = []
    for path in sorted(Path(src_dir).glob("*.csv")):
        book = path.stem  # byztxt code (MAT, MAR, ROM, ...)
        for ch, vs, text in parse_csv(path):
            mapped = byzantine_to_kjv(book, ch, vs)
            if mapped is None:
                omitted += 1
                continue
            code, kch, kvs = mapped
            slot = by_code.setdefault(code, {})
            if (kch, kvs) in slot:
                collisions.append((code, kch, kvs, book, ch, vs))
                continue
            slot[(kch, kvs)] = _clean_greek_nt(text)
    out = {code: sorted((c, v, t) for (c, v), t in d.items()) for code, d in by_code.items()}
    stats = {
        "written": sum(len(v) for v in out.values()),
        "omitted": omitted,
        "collisions": len(collisions),
        "collision_detail": collisions[:20],
        "books": len(out),
    }
    return out, stats


def write_translation(by_code: dict[str, list[tuple[int, int, str]]], dest_dir, verse_total: int) -> None:
    """Write ``<code>.py`` (TRANSLATION/BOOK/VERSES) for each book + ``_meta.yaml``."""
    dest = Path(dest_dir)
    dest.mkdir(parents=True, exist_ok=True)
    for code in sorted(by_code):
        lines = [
            f'"""Translation: {TRANSLATION_ID} · Book: {code}',
            "",
            "AUTO-GENERATED by scripts/extract_byzantine_nt.py.",
            "Do not edit by hand — re-run extraction to regenerate.",
            '"""',
            "",
            f'TRANSLATION = "{TRANSLATION_ID}"',
            f'BOOK = "{code}"',
            "VERSES = [",
        ]
        lines += [f"    ({c}, {v}, {t!r})," for c, v, t in by_code[code]]
        lines.append("]")
        (dest / f"{code}.py").write_text("\n".join(lines) + "\n", encoding="utf-8")

    meta = f"""# Translation metadata — generated by scripts/extract_byzantine_nt.py
# Greek New Testament — Robinson-Pierpont Byzantine Majority Text (accented Unicode).

id: {TRANSLATION_ID}
title: "Greek New Testament (Byzantine Majority Text)"
short_title: "Byzantine GNT"
license: "Public Domain"
source:
  publisher: "Robinson & Pierpont, The New Testament in the Original Greek: Byzantine Textform (byztxt)"
  url: "https://github.com/byztxt/byzantine-majority-text"
  package: "csv-unicode/ccat/no-variants/*.csv (accented Unicode, public-domain text)"
  fetched: 2026-05-23
  source_date: 2005
stats:
  books: {len(by_code)}
  verses: {verse_total}
notes: |
  All 27 NT books of the Robinson-Pierpont Byzantine Majority Text, accented
  polytonic Greek Unicode, mapped to canonical KJV coordinates via
  scripts/core/versification.byzantine_to_kjv. Versification is KJV-standard
  (identity); the Byzantine single-verse omissions (Luke 17:36, Acts 8:37 /
  15:34 / 24:7) are gap-preserved; the one reorder is the Romans doxology
  (KJV 16:25-27 placed at the end of chapter 14 in the Byzantine text). Greek
  is stored PLAIN (the ¶ paragraph marker stripped). Public Domain (Unlicense).
  Regenerable: re-run the extractor.
"""
    (dest / "_meta.yaml").write_text(meta, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    by_code, stats = build_verses(DEFAULT_SOURCE)
    if stats["collisions"]:
        print(f"WARNING: {stats['collisions']} coord collisions: {stats['collision_detail']}")
    write_translation(by_code, TRANSLATIONS_DIR / TRANSLATION_ID, stats["written"])
    print(
        f"wrote {stats['written']} verses across {stats['books']} books "
        f"(omitted {stats['omitted']}; collisions {stats['collisions']}) -> {TRANSLATION_ID}/"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
