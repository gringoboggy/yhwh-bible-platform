#!/usr/bin/env python3
"""One-shot re-ingest of dict-easton note bodies → the FULL (uncapped, ``_HEAD``-fixed)
Easton article, byte-minimal **lockstep** in the SOURCE store (``content/notes/*.py``)
and the baked BASE (``epub_working/index_split_*.html``).

Models ``scripts/_strip_reviewer_scaffold.py`` (the RX-Phase-1 lockstep), but with a
computed old→new body map. Defect #1 of the auto-note re-ingest
(``docs/superpowers/notes/2026-06-06-auto-note-reingest-plan.md`` §1).

Provably-correct pairing (no heuristic)
---------------------------------------
The store was generated by the OLD extractor (cap 480, greedy ``_HEAD``). This one-shot
is a **frozen historical transform**: it regenerates BOTH the old-style body (old regex
+ cap) and the new-style body (fixed regex, no cap) from each source entry, pairs them,
and matches each store note by **exact old-body equality**. So the 640 coordinate
collisions resolve automatically — no coord/headword heuristic, no guessing. (Verified:
this reproduces 3,777 / 3,779 store bodies exactly, 0 ambiguous; 1,650 genuinely change.
The two it cannot reproduce — ``rev 1:8`` f/g, a pre-existing duplicate "A Alpha" with a
non-standard truncation — are left untouched and reported, never silently dropped. They
do not end in ``…`` so the truncation guard still passes.)

Preconditions (ABORT on violation)
----------------------------------
* No source old-body maps to two different new bodies.
* Every changed old body occurs **exactly once** across the source ``.py`` files.
* New bodies contain no double-quote, backslash, or newline (keeps the ``.py`` literal valid).

Base edge cases: a body absent from the base is **skipped with a loud log** (source still
fixed); a body present >1× has **all** occurrences replaced.

Usage
-----
    python3 scripts/_reingest_eastons.py            # dry-run (no writes) — prints the gates
    python3 scripts/_reingest_eastons.py --write    # apply the lockstep replacement
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from scripts.extract_eastons_ccel import SOURCE  # noqa: E402  — just the source path

NOTES_DIR = REPO / "content" / "notes"
BASE_DIR = REPO / "epub_working"

# Frozen regexes: OLD = what built the store (greedy continuation); NEW = the fix
# (negative lookahead so a sentence-case word's lead capital is not grabbed).
_HEAD_OLD = re.compile(r"^([A-Z][A-Z0-9'’\-]*(?:\s+[A-Z0-9'’\-]+)*)")
_HEAD_NEW = re.compile(r"^([A-Z][A-Z0-9'’\-]*(?:\s+[A-Z0-9'’\-]+(?![a-z]))*)")
_MAX_OLD = 480  # the dropped truncation cap
_S2 = re.compile(r"<strong>[^<]*</strong>\s*<strong>([^<]*)</strong>")


def _body(chunk: str, head_re: re.Pattern[str], cap: int, *, escape: bool = False) -> str | None:
    """Reproduce a body for one source entry. ``escape`` XHTML-escapes the prose —
    used for the NEW (shipping) body so a literal &/</> stays well-formed when baked
    verbatim; the OLD-style body stays raw so it matches the store the un-escaping old
    extractor wrote. cap=0 → no truncation."""
    m = head_re.match(chunk)
    if not m:
        return None
    head = m.group(1).strip()
    if len(head) < 2:
        return None
    rest = re.sub(r"\s+", " ", chunk[len(head) :]).strip().replace("\\", "").replace('"', "'")
    if escape:
        rest = rest.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    if cap and len(rest) > cap:
        rest = rest[:cap].rsplit(" ", 1)[0] + "…"
    return f"<strong>Dictionary (Easton's).</strong> <strong>{head}</strong> {rest}"


def old_to_new() -> tuple[dict[str, str], list[str]]:
    """old_style_body → new_style_body, per source entry."""
    text = SOURCE.read_text(encoding="utf-8")
    m: dict[str, str] = {}
    conflicts: list[str] = []
    for chunk in text.split("•")[1:]:
        chunk = chunk.strip()
        ob = _body(chunk, _HEAD_OLD, _MAX_OLD)  # old-style: raw (matches the store)
        nb = _body(chunk, _HEAD_NEW, 0, escape=True)  # new-style: XHTML-safe
        if ob is None or nb is None:
            continue
        if ob in m and m[ob] != nb:
            conflicts.append(ob[:80])
        else:
            m[ob] = nb
    return m, conflicts


def store_dict_easton() -> list[tuple[str, int, int, str, str]]:
    """Every dict-easton note: (book_code, ch, v, suffix, old_body)."""
    out: list[tuple[str, int, int, str, str]] = []
    for p in sorted(NOTES_DIR.glob("*.py")):
        if p.name == "__init__.py":
            continue
        tree = ast.parse(p.read_text(encoding="utf-8"))
        for node in tree.body:
            if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "NOTES" for t in node.targets):
                for t in ast.literal_eval(node.value):
                    if len(t) >= 8 and t[4] == "dict-easton":
                        out.append((p.stem, t[0], t[1], t[2], t[7]))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true", help="apply the lockstep replacement (default: dry-run)")
    args = ap.parse_args(argv)

    src_map, src_conflicts = old_to_new()
    if src_conflicts:
        print(f"⚠ {len(src_conflicts)} source old-bodies map to >1 new body — ABORT")
        for c in src_conflicts[:10]:
            print("   ", c)
        return 2

    store = store_dict_easton()
    mapping: dict[str, str] = {}  # old_body -> new_body (changed only)
    unmatched: list[tuple[str, int, int, str, str]] = []
    for code, ch, v, suffix, old_body in store:
        nb = src_map.get(old_body)
        if nb is None:
            unmatched.append((code, ch, v, suffix, old_body))
        elif nb != old_body:
            mapping[old_body] = nb

    trunc_changed = sum(1 for ob in mapping if re.sub("<[^>]+>", "", ob).rstrip().endswith("…"))
    print(f"store dict-easton notes : {len(store)}")
    print(f"bodies to change        : {len(mapping)}  (of which truncated: {trunc_changed})")
    print(f"unmatched (kept as-is)  : {len(unmatched)}")
    for code, ch, v, suffix, ob in unmatched:
        ell = re.sub("<[^>]+>", "", ob).rstrip().endswith("…")
        h = _S2.search(ob)
        head = h.group(1) if h else "?"
        print(f"    ⚠ {code} {ch}:{v}{suffix} head={head!r} ellipsis={ell} — REVIEW (kept)")

    # validity of new bodies: keep the .py literal valid (no double-quote/backslash/newline)
    # AND keep the baked XHTML well-formed (no raw </>/& outside the <strong> tags — an
    # unescaped char here is what tripped epubcheck RSC-016 before escaping was added).
    def _xhtml_bad(b: str) -> bool:
        inner = b.replace("<strong>", "").replace("</strong>", "")
        return (
            '"' in b
            or "\\" in b
            or "\n" in b
            or "<" in inner
            or ">" in inner
            or bool(re.search(r"&(?!(amp|lt|gt|quot|apos|#\d+|#x[0-9a-fA-F]+);)", inner))
        )

    bad = [nb for nb in mapping.values() if _xhtml_bad(nb)]
    if bad:
        print(f'⚠ {len(bad)} new bodies are XHTML-unsafe (raw " \\ newline </>/&) — ABORT')
        for nb in bad[:5]:
            print(f"    {nb[:90]!r}")
        return 2

    src_texts = {p: p.read_text(encoding="utf-8") for p in sorted(NOTES_DIR.glob("*.py")) if p.name != "__init__.py"}
    base_texts = {p: p.read_text(encoding="utf-8") for p in sorted(BASE_DIR.glob("index_split_*.html"))}

    # precondition: each changed old body must be FOUND in source (≥1). A body that
    # appears >1× is a pre-existing duplicate note (e.g. DALMANUTHA) — all occurrences
    # are the same content, so replace-all is correct (the body string is distinctive
    # to a dict-easton note, so it cannot collide with unrelated text).
    src_count = {ob: sum(t.count(ob) for t in src_texts.values()) for ob in mapping}
    src_missing = [ob for ob, c in src_count.items() if c == 0]
    src_multi = {ob: c for ob, c in src_count.items() if c > 1}
    if src_missing:
        print(f"⚠ {len(src_missing)} changed old bodies NOT found in source (.py) — ABORT")
        for ob in src_missing[:10]:
            print(f"    {ob[:80]!r}")
        return 2

    base_count = {ob: sum(t.count(ob) for t in base_texts.values()) for ob in mapping}
    base_miss = [ob for ob, c in base_count.items() if c == 0]
    base_multi = [ob for ob, c in base_count.items() if c > 1]
    print(f"source .py : {len(mapping)} old bodies found ✓  ({len(src_multi)} appear >1× → all occurrences replaced)")
    for dup_body, dup_count in src_multi.items():
        h = _S2.search(dup_body)
        print(f"    source-multi (x{dup_count}, all replaced): head={h.group(1) if h else '?'!r}")
    single = len(mapping) - len(base_miss) - len(base_multi)
    print(f"base .html : missing {len(base_miss)} / multi {len(base_multi)} / single {single}")
    for ob in base_miss:
        h = _S2.search(ob)
        print(f"    base-miss (source-only, skip base): head={h.group(1) if h else '?'!r}  {ob[:70]!r}")

    if not args.write:
        print("\nDRY-RUN — no files written. Re-run with --write to apply.")
        return 0

    src_written = base_written = base_repl = 0
    for p, text in src_texts.items():
        new_text = text
        for ob, nb in mapping.items():
            if ob in new_text:
                new_text = new_text.replace(ob, nb)
        if new_text != text:
            p.write_text(new_text, encoding="utf-8")
            src_written += 1
    for p, text in base_texts.items():
        new_text = text
        for ob, nb in mapping.items():
            cnt = new_text.count(ob)
            if cnt:
                new_text = new_text.replace(ob, nb)
                base_repl += cnt
        if new_text != text:
            p.write_text(new_text, encoding="utf-8")
            base_written += 1
    print(f"\nWROTE: src={src_written} base={base_written} ({base_repl} occ); {len(base_miss)} src-only.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
