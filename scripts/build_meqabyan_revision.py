#!/usr/bin/env python3
"""build_meqabyan_revision.py — assemble per-book Geʽez-revision markdown
from content/divergence/meqabyan_geez_divergence.json.

Seeded at δ.1.0 (2026-05-14). Per the Phase-4 working method (see
`project_maccabees_expansion/02_METHODOLOGY.md`, summarized in
`dev/PHASE4_MEQABYAN_TRACKER.md`), each δ.1.x batch ship appends
verse-keyed entries to the divergence JSON, then this tool regenerates
the three per-book revision markdown files:

  exports/meqabyan_geez_revision/1Mq_geez_revision.md
  exports/meqabyan_geez_revision/2Mq_geez_revision.md
  exports/meqabyan_geez_revision/3Mq_geez_revision.md

Honesty rules enforced (per the JSON's `_meta.honesty_rules`):

- **Confidence threshold:** entries with `confidence < 0.8` are
  REFUSED unless `--allow-low-confidence` is passed with an explicit
  reviewer sign-off message (`--reviewer "Name <email>"`).
- **Page-image authority:** the tool does not consume OCR text;
  it consumes operator-produced entries that the operator certifies
  derive from 350 dpi page-image reads. The `page_image_verified`
  flag on each entry must be `true` or the entry is REFUSED.
- **v1 English immutability:** the tool produces revision markdown
  in `exports/meqabyan_geez_revision/` ONLY. It NEVER modifies
  `content/translations/english/` or `content/notes/`.

At δ.1.0 (this seed ship), the JSON has `entries: []` so the tool
produces empty per-book revision markdown files (with headers + the
"0 entries this revision" placeholder). δ.1.x.A-G batches append
entries; δ.1.Z arc-close validates 67/67 chapter coverage.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


REPO = Path(__file__).resolve().parent.parent
DIVERGENCE_JSON = REPO / "content" / "divergence" / "meqabyan_geez_divergence.json"
OUTPUT_DIR = REPO / "exports" / "meqabyan_geez_revision"

# Per-book metadata (matches `_meta.chapters_per_book` in the divergence JSON).
BOOKS = [
    ("mq1", "1 Mäqabyan", 36),
    ("mq2", "2 Mäqabyan", 21),
    ("mq3", "3 Mäqabyan", 10),
]


def load_divergence_json(path: Path = DIVERGENCE_JSON) -> dict:
    """Load and minimally validate the divergence JSON."""
    if not path.is_file():
        raise SystemExit(f"divergence JSON not found: {path}")
    data = json.loads(path.read_text(encoding="utf-8"))
    if "_meta" not in data:
        raise SystemExit("divergence JSON missing _meta block")
    if "entries" not in data:
        raise SystemExit("divergence JSON missing entries list")
    return data


def validate_entry(entry: dict, allow_low_confidence: bool, reviewer: str | None) -> tuple[bool, str]:
    """Return (ok, reason). Refuse entries that violate honesty rules."""
    required = {"book", "chapter", "verse", "geez_text", "geez_revised_english", "divergence_class", "confidence"}
    missing = required - entry.keys()
    if missing:
        return False, f"missing required fields: {sorted(missing)}"

    if entry.get("page_image_verified") is not True:
        return False, "page_image_verified must be true (Phase-4 honesty rule: page-image authority)"

    conf = entry.get("confidence", 0)
    if conf < 0.8:
        if not allow_low_confidence:
            return False, f"confidence {conf} < 0.8 floor (use --allow-low-confidence + --reviewer to override)"
        if not reviewer:
            return False, f"confidence {conf} < 0.8 requires --reviewer 'Name <email>' for sign-off"

    valid_classes = {"lexical", "structural", "content", "numbering", "trivial"}
    if entry["divergence_class"] not in valid_classes:
        return False, f"divergence_class must be one of {sorted(valid_classes)}; got {entry['divergence_class']!r}"

    return True, "ok"


def assemble_book_markdown(book_code: str, book_title: str, total_chapters: int, entries: list[dict]) -> str:
    """Render per-book revision markdown. Entries are filtered to the
    given book_code; verses within each chapter are ordered."""
    book_entries = sorted(
        (e for e in entries if e.get("book") == book_code),
        key=lambda e: (e.get("chapter", 0), e.get("verse", 0)),
    )

    lines: list[str] = []
    lines.append(f"# {book_title} — Phase-4 Geʽez-revision (page-image-tier1)")
    lines.append("")
    lines.append(
        f"Generated by `scripts/build_meqabyan_revision.py` from "
        f"`content/divergence/meqabyan_geez_divergence.json`. "
        f"Entries this revision: **{len(book_entries)}** across "
        f"**{total_chapters} chapters** of {book_title}."
    )
    lines.append("")
    lines.append(
        "Honesty rules: page-image authority (350 dpi); v1 English "
        "immutable during δ.1.x; confidence ≥ 0.8 (or reviewer override)."
    )
    lines.append("")

    if not book_entries:
        lines.append("## 0 entries this revision")
        lines.append("")
        lines.append(
            f"_This file was generated by a δ.1.0 seed ship "
            f"({book_title} has not yet been touched by any δ.1.x.A-G "
            f"batch.) Per-chapter and per-verse entries will appear "
            f"in subsequent batches; the tracker at `dev/PHASE4_"
            f"MEQABYAN_TRACKER.md` records cumulative status._"
        )
        lines.append("")
        return "\n".join(lines)

    current_chapter = None
    for entry in book_entries:
        ch = entry.get("chapter")
        v = entry.get("verse")
        if ch != current_chapter:
            lines.append(f"## {book_title} Chapter {ch}")
            lines.append("")
            current_chapter = ch
        lines.append(f"### Verse {ch}:{v}")
        lines.append("")
        lines.append(f"**Geʽez (page-image):** {entry.get('geez_text', '—')}")
        lines.append("")
        if entry.get("amharic_text"):
            lines.append(f"**Amharic (page-image):** {entry['amharic_text']}")
            lines.append("")
        if entry.get("v1_english"):
            lines.append(f"**v1 English (unchanged):** {entry['v1_english']}")
            lines.append("")
        lines.append(f"**[GZ] Phase-4 revised English:** {entry['geez_revised_english']}")
        lines.append("")
        lines.append(
            f"_Divergence class:_ `{entry['divergence_class']}` _·_ "
            f"_Confidence:_ {entry['confidence']:.2f} _·_ "
            f"_Operator session:_ `{entry.get('operator_session', '—')}`"
        )
        if entry.get("divergence_note"):
            lines.append("")
            lines.append(f"_Note:_ {entry['divergence_note']}")
        lines.append("")

    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument(
        "--divergence-json",
        type=Path,
        default=DIVERGENCE_JSON,
        help="Path to the divergence JSON (default: content/divergence/meqabyan_geez_divergence.json)",
    )
    ap.add_argument(
        "--output-dir",
        type=Path,
        default=OUTPUT_DIR,
        help="Output directory for per-book revision markdown (default: exports/meqabyan_geez_revision/)",
    )
    ap.add_argument(
        "--allow-low-confidence",
        action="store_true",
        help="Allow entries with confidence < 0.8 (requires --reviewer)",
    )
    ap.add_argument(
        "--reviewer",
        type=str,
        default=None,
        help="Reviewer name + email for low-confidence override sign-off",
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="Validate the divergence JSON + report status; do not write outputs",
    )
    args = ap.parse_args(argv)

    data = load_divergence_json(args.divergence_json)
    entries = data.get("entries", [])

    valid_entries: list[dict] = []
    rejected: list[tuple[dict, str]] = []
    for entry in entries:
        ok, reason = validate_entry(entry, args.allow_low_confidence, args.reviewer)
        if ok:
            valid_entries.append(entry)
        else:
            rejected.append((entry, reason))

    print(f"Loaded {len(entries)} entries from {args.divergence_json}")
    print(f"  Accepted: {len(valid_entries)}")
    print(f"  Rejected: {len(rejected)}")
    for entry, reason in rejected:
        ref = f"{entry.get('book', '?')} {entry.get('chapter', '?')}:{entry.get('verse', '?')}"
        print(f"    [reject] {ref}: {reason}")

    if rejected and not args.allow_low_confidence:
        print(
            "\nERROR: rejected entries above. Fix the divergence JSON, or "
            "use --allow-low-confidence + --reviewer 'Name <email>'.",
            file=sys.stderr,
        )
        return 2

    if args.check:
        print("\n--check: no output written.")
        return 0

    args.output_dir.mkdir(parents=True, exist_ok=True)
    for book_code, book_title, total_chapters in BOOKS:
        body = assemble_book_markdown(book_code, book_title, total_chapters, valid_entries)
        target = args.output_dir / f"{book_code.upper()}_geez_revision.md"
        target.write_text(body, encoding="utf-8")
        print(f"  wrote {target.relative_to(REPO)}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
